"""
=== Управление магами через консоль ===

1. Перемещение мага:
   `(move-wizard "Гэндальф" (dx dy))`
   Пример: `(move-wizard "Гэндальф" (1 0))` - переместить Гэндальфа на 1 клетку вправо
   dx: 1 (вправо), -1 (влево)
   dy: 1 (вниз), -1 (вверх)

2. Выбор заклинания:
   `(select-spell "Имя_мага" "заклинание")`
   Доступные заклинания:
   - "огненный шар" (урон: 30, мана: 20, дальность: 5)
   - "ледяной осколок" (урон: 20, мана: 15, дальность: 4)
   - "молния" (урон: 40, мана: 35, дальность: 6)
   Пример: `(select-spell "Гэндальф" "молния")`

3. Применение заклинания:
   `(cast-spell "Имя_мага" "заклинание" x y)`
   Пример: `(cast-spell "Гэндальф" "огненный шар" 10 5)`
   x, y - координаты цели на карте

4. Получение здоровья волшебника:
   `(get-wizard-health "Имя_мага")`
   Возвращает текущее здоровье указанного волшебника

5. Проверка видимости волшебника:
   `(is-wizard-visible "Наблюдатель" "Цель")`
   Возвращает true, если цель видна наблюдателю

6. Получение расстояния между волшебниками:
   `(get-distance "Маг1" "Маг2")`
   Возвращает манхэттенское расстояние между двумя волшебниками

7. Переключение ИИ:
   `(toggle-ai)`
   Включает/выключает автоматическое выполнение стратегий

Математические функции:
- `(+ a b c ...)` - сложение
- `(- a b c ...)` - вычитание
- `(* a b c ...)` - умножение
- `(/ a b c ...)` - деление
- `(< a b)`, `(> a b)`, `(<= a b)`, `(>= a b)`, `(= a b)` - сравнения
- `(random n)` - случайное число от 0 до n-1
- `(mod a b)` - остаток от деления
- `(sqrt n)` - квадратный корень
- `(abs n)` - абсолютное значение
- `(min a b c ...)` - минимум
- `(max a b c ...)` - максимум

Логические функции:
- `(and a b c ...)` - логическое И
- `(or a b c ...)` - логическое ИЛИ
- `(not a)` - логическое НЕ
- `(if условие то иначе)` - условное выражение

Функции для работы со списками:
- `(list a b c ...)` - создать список
- `(car список)` - первый элемент
- `(cdr список)` - хвост списка
- `(cons элемент список)` - добавить элемент в начало
- `(length список)` - длина списка

Управляющие конструкции:
- `(progn выр1 выр2 ...)` - выполнить последовательность выражений
- `(cond (усл1 знач1) (усл2 знач2) ...)` - множественное ветвление
- `(let ((var1 val1) (var2 val2)) body)` - локальные переменные

Консольные команды:
- `help` - показать эту справку
- `clear` - очистить историю команд
- `history` - показать историю команд
- Tab - переключение между консолями волшебников
- Стрелки вверх/вниз - навигация по истории команд
"""
